window.I18N = (() => {
  const MAP = {
    'Lj': 'Љ', 'LJ': 'Љ', 'lj': 'љ', 'Nj': 'Њ', 'NJ': 'Њ', 'nj': 'њ', 'Dž': 'Џ', 'DŽ': 'Џ', 'dž': 'џ',
    A: 'А', B: 'Б', C: 'Ц', Č: 'Ч', Ć: 'Ћ', D: 'Д', Đ: 'Ђ', E: 'Е', F: 'Ф', G: 'Г', H: 'Х', I: 'И', J: 'Ј', K: 'К',
    L: 'Л', M: 'М', N: 'Н', O: 'О', P: 'П', R: 'Р', S: 'С', Š: 'Ш', T: 'Т', U: 'У', V: 'В', Z: 'З', Ž: 'Ж',
    Q: 'К', W: 'В', X: 'Кс', Y: 'И',
    a: 'а', b: 'б', c: 'ц', č: 'ч', ć: 'ћ', d: 'д', đ: 'ђ', e: 'е', f: 'ф', g: 'г', h: 'х', i: 'и', j: 'ј', k: 'к',
    l: 'л', m: 'м', n: 'н', o: 'о', p: 'п', r: 'р', s: 'с', š: 'ш', t: 'т', u: 'у', v: 'в', z: 'з', ž: 'ж',
    q: 'к', w: 'в', x: 'кс', y: 'и'
  };
  const RE = /Lj|LJ|lj|Nj|NJ|nj|Dž|DŽ|dž|[A-Za-zČĆĐŠŽčćđšž]/g;
  // Transliterate, leaving {protected} segments in Latin.
  const toCyr = (s) => s.split(/(\{[^}]*\})/).map((part) =>
    part.startsWith('{') ? part : part.replace(RE, (m) => MAP[m] || m)).join('');
  const unbrace = (s) => s.replace(/[{}]/g, '');
  return { toCyr, unbrace };
})();
